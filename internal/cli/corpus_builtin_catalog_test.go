var corpusBuiltinMethodMasks = buildCorpusBuiltinMethodMasks()

var corpusShadowedBuiltinMethods = map[string]bool{
	"ENCODETOUNI": true, "GETTIME": true, "OUTPUTLOG": true, "POWER": true,
	"PRINTCPERLINE": true, "SAVENOS": true, "VARSIZE": true,
}

func buildCorpusBuiltinMethodMasks() map[string]uint8 {
	m := make(map[string]uint8)
	for _, name := range strings.Fields(corpusBaseBuiltinMethods) {
		m[strings.ToUpper(name)] |= 1
	}
	for _, name := range strings.Fields(corpusModernBuiltinMethods) {
		m[strings.ToUpper(name)] |= 2
	}
	return m
}

func corpusBuiltinMethod(command string, dialect format.Dialect) bool {
	if corpusShadowedBuiltinMethods[command] && (command != "OUTPUTLOG" || dialect != format.EMEE) {
		return false
	}
	mask := corpusBuiltinMethodMasks[command]
	switch dialect {
	case format.Emuera1824:
		return mask&1 != 0
	case format.EMEE:
		return mask&2 != 0
	default:
		return mask == 3
	}
}
